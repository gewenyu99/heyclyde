// Build the inlined styles and previews for the Worker and chat cards. Run: node design/build.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { AUTH_PROVIDERS, providerBlock } from "./auth.mjs";

const here = new URL(".", import.meta.url);
const legacy = new URL("../memory/design/", here);
const min = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\s+/g, " ").replace(/\s*([{}:;,>])\s*/g, "$1").trim();
const read = (name) => min(readFileSync(new URL(name, here), "utf8"));

// AUTH_CSS (auth.css) is the sign-in pages' only, so the chat cards below never carry it.
writeFileSync(new URL("css.js", legacy), `// Generated by memory/design/build.mjs from tokens.css, components.css and auth.css. Don't edit; edit the CSS and rerun.
export const TOKENS_CSS = ${JSON.stringify(read("tokens.css"))};
export const COMPONENTS_CSS = ${JSON.stringify(read("components.css"))};
export const FONTS_CSS = ${JSON.stringify(read("fonts.css"))};
export const AUTH_CSS = ${JSON.stringify(read("auth.css"))};
`);

// The provider buttons, copied beside css.js so the Worker reads both from memory/design and a change here redeploys it.
writeFileSync(new URL("auth.js", legacy), `// Generated by memory/design/build.mjs from design/auth.mjs. Don't edit; edit that and rerun.\n${readFileSync(new URL("auth.mjs", here), "utf8")}`);

// The chat cards (R67) run in the memory function, which can't read files outside its folder once deployed, so they get a
// copy: the tokens, the components and the lockup. harness/test/memory/ui.test.ts fails while the copy differs. The cards
// are server surface, so a change here needs a SERVER_VERSION bump (harness/test/memory/version.test.ts says which hash).
{
  const brand = readFileSync(new URL("brand.js", here), "utf8");
  const lockup = JSON.parse(/export const LOGO_LOCKUP = (".*");/.exec(brand)[1]);
  const target = new URL("../memory/supabase/functions/memory/ui/design.ts", here);
  const output = `// Generated by memory/design/build.mjs: Clyde's design system for the chat cards (R67). Don't edit; edit memory/design and rerun.
export const TOKENS_CSS = ${JSON.stringify(read("tokens.css"))};
export const COMPONENTS_CSS = ${JSON.stringify(read("components.css"))};
export const LOGO_LOCKUP = ${JSON.stringify(lockup)};
`;
  if (!existsSync(target) || readFileSync(target, "utf8") !== output) writeFileSync(target, output);
}

// Render the previews at their existing URLs with CSS and inline art expanded from the source markers.
for (const name of readdirSync(new URL("src/", here)).filter((n) => n.endsWith(".html"))) {
  const src = readFileSync(new URL(`src/${name}`, here), "utf8");
  const brand = readFileSync(new URL("brand.js", here), "utf8");
  const logo = (name) => JSON.parse(new RegExp(`export const ${name} = (".*");`).exec(brand)[1]);
  const out = src.replace(/<!-- @inline ([a-z]+\.css) -->/g, (_, file) => read(file))
    .replace(/<!-- @logo (lockup|mark) -->/g, (_, k) => logo(k === "lockup" ? "LOGO_LOCKUP" : "LOGO_MARK"))
    .replace(/<!-- @include ([a-z/.-]+) -->/g, (_, file) => readFileSync(new URL(file, here), "utf8"))
    .replace(/<!-- @auth providers -->/g, () => providerBlock(AUTH_PROVIDERS));
  writeFileSync(new URL(name, legacy), `<!-- Generated by memory/design/build.mjs from src/${name}. Edit the source and rerun. -->\n${out}`);
}

// Embed the same assets in the native Paseo client bundle.
await import("../plugins/paseo/sync-brand.mjs");
