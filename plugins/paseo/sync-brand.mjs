// The Paseo client bundle cannot import CSS or SVG files. Export the same source assets it embeds.
import { readFileSync, writeFileSync } from "node:fs";
const source = new URL("../../design/", import.meta.url);
const read = (file) => readFileSync(new URL(file, source), "utf8");
const css = read("tokens.css");
const blocks = [...css.matchAll(/\{([^{}]*--cl-paper-0:[^{}]*)\}/g)].map((m) => m[1]);
const roles = [
  "paper-0",
  "paper-1",
  "paper-2",
  "ink",
  "ink-2",
  "ink-3",
  "carbon",
  "carbon-ink",
  "carbon-wash",
  "carbon-copy",
  "on-carbon",
  "rule",
  "rule-strong",
  "edge",
  "sticky",
  "sticky-strip",
  "sticky-edge",
  "ok",
  "warn",
  "bad",
  "ok-wash",
  "warn-wash",
  "bad-wash",
];
function palette(block) {
  return Object.fromEntries(roles.map((role) => {
    const match = block.match(new RegExp("--cl-" + role + ":\\s*(#[0-9a-fA-F]{6})"));
    if (!match) throw Error("Missing design token " + role);
    return [role, match[1]];
  }));
}
const theme = { light: palette(blocks[0]), dark: palette(blocks.at(-1)) };
const art = {};
for (const scheme of ["light", "dark"]) {
  art[scheme] = {};
  for (const name of ["mark", "lockup"]) {
    art[scheme][name] = { svg: read("brand/clyde-" + name + "-" + scheme + ".svg").trim() };
  }
}
const text = "// Generated by sync-brand.mjs from Clyde’s design system.\nexport const palette = " +
  JSON.stringify(theme, null, 2) + " as const;\nexport const artwork = " + JSON.stringify(art, null, 2) +
  " as const;\n";
const out = new URL("client/brand.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    throw Error("Run node sync-brand.mjs");
  }
} else writeFileSync(out, text);
